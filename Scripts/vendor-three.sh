#!/usr/bin/env bash
# Vendor the exact three.js build used by the 3D model viewer.
#
# This is a maintainer script, not a build step. It downloads one pinned npm
# tarball, verifies its checksum, and copies only the loaders the viewer
# imports plus their transitive dependencies. Run it again only when the
# pinned version changes and the import closure has been re-checked.
set -euo pipefail

VERSION="0.186.1"
TARBALL_SHA512="6e515ea9be3dc110921941a3ee0b697e74861f2da5c0393de11854992d5cfe14dbcbbd24bc285b5a9909e0f9b5dfdd0bab3cef4e6ce05ca1cf11a7c9c026fc8c"
TARBALL_URL="https://registry.npmjs.org/three/-/three-${VERSION}.tgz"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/Sources/Sonovo/Resources/ModelViewer/vendor/three"
LICENSE_DEST="$ROOT/Vendor/three-LICENSE.txt"

FILES=(
    "build/three.module.js"
    "build/three.core.js"
    "examples/jsm/controls/OrbitControls.js"
    "examples/jsm/environments/RoomEnvironment.js"
    "examples/jsm/loaders/GLTFLoader.js"
    "examples/jsm/loaders/DRACOLoader.js"
    "examples/jsm/loaders/KTX2Loader.js"
    "examples/jsm/loaders/OBJLoader.js"
    "examples/jsm/loaders/MTLLoader.js"
    "examples/jsm/loaders/STLLoader.js"
    "examples/jsm/loaders/PLYLoader.js"
    "examples/jsm/loaders/FBXLoader.js"
    "examples/jsm/loaders/3MFLoader.js"
    "examples/jsm/loaders/USDLoader.js"
    "examples/jsm/loaders/usd/USDAParser.js"
    "examples/jsm/loaders/usd/USDCParser.js"
    "examples/jsm/loaders/usd/USDComposer.js"
    "examples/jsm/loaders/ColladaLoader.js"
    "examples/jsm/loaders/collada/ColladaParser.js"
    "examples/jsm/loaders/collada/ColladaComposer.js"
    "examples/jsm/loaders/TGALoader.js"
    "examples/jsm/libs/fflate.module.js"
    "examples/jsm/libs/meshopt_decoder.module.js"
    "examples/jsm/libs/ktx-parse.module.js"
    "examples/jsm/libs/zstddec.module.js"
    "examples/jsm/libs/draco/gltf/draco_decoder.wasm"
    "examples/jsm/libs/draco/gltf/draco_wasm_wrapper.js"
    "examples/jsm/libs/basis/basis_transcoder.wasm"
    "examples/jsm/libs/basis/basis_transcoder.js"
    "examples/jsm/utils/BufferGeometryUtils.js"
    "examples/jsm/utils/SkeletonUtils.js"
    "examples/jsm/utils/WorkerPool.js"
    "examples/jsm/curves/NURBSCurve.js"
    "examples/jsm/curves/NURBSUtils.js"
    "examples/jsm/math/ColorSpaces.js"
)

WORK="$(mktemp -d "${TMPDIR:-/tmp}/sonovo-three.XXXXXX")"
STAGING="${DEST}.staging.$$"
trap 'rm -rf "$WORK" "$STAGING"' EXIT

cd "$WORK"
curl -fsSL --max-time 120 -o three.tgz "$TARBALL_URL"

ACTUAL="$(shasum -a 512 three.tgz | awk '{print $1}')"
if [ "$ACTUAL" != "$TARBALL_SHA512" ]; then
    echo "three.js tarball checksum mismatch" >&2
    echo "expected $TARBALL_SHA512" >&2
    echo "actual   $ACTUAL" >&2
    exit 1
fi

tar -xzf three.tgz
PACKAGE="$WORK/package"

# Assemble a complete tree next to the destination. The old tree is replaced
# only after every file and the checksum manifest are ready, so a failed
# download or copy cannot leave a mixed-version vendor directory.
rm -rf "$STAGING"
mkdir -p "$STAGING"
for file in "${FILES[@]}"; do
    if [ ! -s "$PACKAGE/$file" ]; then
        echo "expected file missing or empty: $file" >&2
        exit 1
    fi
    mkdir -p "$STAGING/$(dirname "$file")"
    cp "$PACKAGE/$file" "$STAGING/$file"
done

(
    cd "$STAGING"
    find . -type f ! -name 'SHA256SUMS' ! -name 'VENDOR.md' -print0 \
        | sort -z \
        | xargs -0 shasum -a 256 > SHA256SUMS
)

cat > "$STAGING/VENDOR.md" <<EOF
# Vendored three.js

- **Version:** ${VERSION} (r186)
- **Source:** ${TARBALL_URL}
- **Tarball SHA-512:** ${TARBALL_SHA512}
- **License:** MIT. The full text is at \`Vendor/three-LICENSE.txt\`.

Only the files listed in \`Scripts/vendor-three.sh\` are copied: the two build
files, the loaders the viewer uses, and their transitive imports. Re-run that
script to refresh them; do not hand-edit files in this directory.

\`SHA256SUMS\` is generated by the same script.
EOF

cp "$PACKAGE/LICENSE" "$LICENSE_DEST"
rm -rf "$DEST"
mv "$STAGING" "$DEST"

echo "vendored three.js $VERSION into $DEST"
