#!/usr/bin/env python3
"""Generate the design-token ledger from Sources/Sonovo/Theme.swift."""

from __future__ import annotations

import argparse
import re
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / "Sources" / "Sonovo" / "Theme.swift"

TOKEN = re.compile(r"^\s*static let (\w+)(?::\s*([^=]+?))?\s*=\s*(.+)$")
ENUM = re.compile(r"^\s*(?:enum|struct)\s+(\w+)")


def parse() -> OrderedDict[str, list[tuple[str, str]]]:
    categories: OrderedDict[str, list[tuple[str, str]]] = OrderedDict()
    stack: list[str] = []
    lines = THEME.read_text().splitlines()
    index = 0

    while index < len(lines):
        line = lines[index]
        stripped = line.strip()

        enum_match = ENUM.match(line)
        if enum_match and not stripped.startswith("//"):
            stack.append(enum_match.group(1))

        token_match = TOKEN.match(line)
        if token_match and stack:
            name, _, value = token_match.groups()
            value = value.strip()
            balance = value.count("(") - value.count(")")
            if balance > 0:
                parts = [value]
                while balance > 0 and index + 1 < len(lines):
                    index += 1
                    part = lines[index].strip()
                    parts.append(part)
                    balance += part.count("(") - part.count(")")
                value = " ".join(parts)
            category = ".".join(stack[1:]) or "AppTheme"
            categories.setdefault(category, []).append((name, value))

        if stripped == "}" and stack:
            stack.pop()

        index += 1

    return categories


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate the design-token ledger from Theme.swift."
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Path of the generated Markdown ledger.",
    )
    args = parser.parse_args()
    ledger = args.output.expanduser()

    categories = parse()

    out: list[str] = []
    out.append("# Design Token Ledger")
    out.append("")
    out.append(
        "Every visual value in the app lives in `Sources/Sonovo/Theme.swift`. "
        "View files reference tokens; they do not carry numeric design literals."
    )
    out.append("")
    out.append("This file is generated by `Scripts/generate_token_ledger.py`. Do not hand-edit it.")
    out.append("")
    out.append("## Enforcement")
    out.append("")
    out.append("```sh")
    out.append("./Scripts/check-design-tokens.sh")
    out.append("```")
    out.append("")
    out.append(
        "The check fails on raw numbers in visual modifiers (`padding`, `frame`, "
        "`font`, `cornerRadius`, `lineWidth`, `opacity`, `tracking`, `lineSpacing`, "
        "`shadow`, `offset`, `aspectRatio`), raw colors, and raw material names."
    )
    out.append("")
    out.append("## Allowed system semantics")
    out.append("")
    out.append(
        "Apple semantic values are already adaptive and are not duplicated: "
        "`.primary`, `.secondary`, `.tertiary`, `.quaternary`, `.accentColor`, "
        "`.clear`, `.infinity`, and standard `controlSize` values. "
        "Colors wrapped by the palette are listed below."
    )
    out.append("")
    out.append("## Content renderers")
    out.append("")
    out.append(
        "These files render content rather than chrome, so their geometry and "
        "algorithm parameters are not design tokens:"
    )
    out.append("")
    out.append("- `Sources/Sonovo/CoastalSceneView.swift` — procedural scene artwork.")
    out.append("- `Sources/Sonovo/WaveformView.swift` — audio waveform geometry and amplitude.")
    out.append("- `Sources/Sonovo/SampleHTML.swift` — the embedded storyboard document.")
    out.append("")
    out.append(
        "The Ghostty theme backgrounds in `Resources/ghostty-themes/light.conf` and "
        "`dark.conf` mirror `Palette.terminalLight` and `Palette.terminalDark`, which "
        "match `NSColor.textBackgroundColor`. The navigator and inspector use the "
        "same `Palette.text` base, so every pane in the workspace shares one canvas."
    )
    out.append("")
    out.append("## Radius hierarchy")
    out.append("")
    out.append("| Role | Token | Value |")
    out.append("| --- | --- | --- |")
    out.append("| Thin accent | `Radius.line` | 1 |")
    out.append("| Micro control | `Radius.micro` | 4 |")
    out.append("| Control / tab / field | `Radius.control` | 6 |")
    out.append("| Nested panel / note card | `Radius.panel` | 8 |")
    out.append("| Content surface / canvas / card | `Radius.surface` | 12 |")
    out.append("")
    out.append(
        "Capsules and circles are intentional exceptions. The canvas corner "
        "setting can override the surface radius with 0, 12, or 16."
    )
    out.append("")
    out.append("## Tokens")
    out.append("")

    for category, tokens in categories.items():
        out.append(f"### `AppTheme.{category}`")
        out.append("")
        out.append("| Token | Value |")
        out.append("| --- | --- |")
        for name, value in tokens:
            out.append(f"| `{name}` | `{value}` |")
        out.append("")

    ledger.parent.mkdir(parents=True, exist_ok=True)
    ledger.write_text("\n".join(out).rstrip() + "\n")
    total = sum(len(tokens) for tokens in categories.values())
    print(f"wrote {ledger} with {total} tokens in {len(categories)} categories")


if __name__ == "__main__":
    main()
